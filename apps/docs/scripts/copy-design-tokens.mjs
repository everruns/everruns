// Publishes the app's Slate tokens for the design system pages (/design-system/).
//
// Decision: the design system site never keeps its own copy of the tokens. It
// reads apps/ui/src/app/design-system.css, the runtime source of truth, at build
// time, so a token change in the app shows up on the site with no second edit.
// The examples render inside `.ds-example`, so the app tokens are scoped there
// and do not disturb the docs theme. Light values hang off `:root` in the app;
// dark values off `.dark`, which the docs express as `[data-theme="dark"]`.
// See knowledge/ui/design-system.md.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../ui/src/app/design-system.css");
const outDir = join(here, "../src/generated");

/** Custom properties declared directly in the first `selector { ... }` block. */
export function declarations(css, selector) {
  const start = css.search(new RegExp(`(^|\\n)\\s*${selector.replace(".", "\\.")}\\s*\\{`));
  if (start < 0) throw new Error(`design-system.css has no ${selector} block`);
  const open = css.indexOf("{", start);
  const close = css.indexOf("}", open);
  const tokens = [];
  let note = "";
  for (const raw of css.slice(open + 1, close).split("\n")) {
    const line = raw.trim();
    const comment = line.match(/^\/\*\s*(.*?)\s*(\*\/)?$/);
    if (comment && !line.startsWith("--")) {
      note = comment[1].replace(/\*\/$/, "").trim();
      continue;
    }
    const decl = line.match(/^(--[\w-]+):\s*([^;]+);/);
    if (decl) {
      tokens.push({ name: decl[1], value: decl[2].trim(), note });
      note = "";
    }
  }
  return tokens;
}

const css = readFileSync(source, "utf8");
const light = declarations(css, ":root");
const dark = declarations(css, ".dark");

// The utilities and motion after the token blocks (dot grid, .icon-sharp,
// row-enter, pulse, shimmer, loading wave) are plain CSS with app-only class
// names, so they are copied as they are; only the app's `.dark` class becomes
// the docs' `[data-theme="dark"]`.
const utilitiesStart = css.indexOf(".bg-brand-dots");
if (utilitiesStart < 0) throw new Error("design-system.css has no .bg-brand-dots utility");
const utilities = css.slice(utilitiesStart).replace(/(^|\n|,\s*)\.dark /g, '$1:root[data-theme="dark"] ');

const block = (tokens) => tokens.map((t) => `  ${t.name}: ${t.value};`).join("\n");
const output = `/* Generated by scripts/copy-design-tokens.mjs from apps/ui/src/app/design-system.css. Do not edit. */
.ds-example {
${block(light)}
  color-scheme: light;
}
:root[data-theme="dark"] .ds-example {
${block(dark)}
  color-scheme: dark;
}

${utilities}`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "app-tokens.css"), output);
writeFileSync(join(outDir, "app-tokens.json"), `${JSON.stringify({ light, dark }, null, 2)}\n`);
console.log(`[copy-design-tokens] ${light.length} light and ${dark.length} dark tokens written to src/generated/`);
