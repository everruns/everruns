#!/usr/bin/env python3
"""Turn the coding profile into llmsim scenarios, and measure how close they are.

  generate.py            # rewrite crates/drivers/llmsim/scenarios/coding-profile.json
  generate.py --check    # exit 1 if the committed scenarios are stale

The profile's distributions become eleven scenarios, `coding-p01`, `coding-p10` .. `coding-p90`,
`coding-p99`, at those percentiles of model calls per turn. Played with equal weight
(`agentd-drive --scenarios coding-p01,coding-p10,...,coding-p99`), their mixture has the
profile's median and p90 of model calls, tool output sizes and output tokens.
Tool outputs are real bytes (`seq 1 N` in the bash tool) sized at evenly
spread quantiles of the profile's tool output distribution; no content from
any real session is used.

Decisions:
- Deterministic: no random draws, so the file only changes when the profile
  or this generator does, and the drift guard can compare bytes.
- Each distribution is a log-normal through the profile's median and p90,
  the same right-skewed shape llmsim uses for its own `{median, p99}` ranges.
- Context growth within a turn comes from the outputs accumulating in the
  history; llmsim cannot pad context otherwise.
"""

import argparse
import json
import math
import os
import sys
from statistics import NormalDist

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
PROFILE = os.path.join(HERE, "coding-profile.json")
OUT = os.path.join(REPO, "crates", "drivers", "llmsim", "scenarios", "coding-profile.json")
# Eleven points at 0, 0.1 .. 0.9, 1 (clipped to the 1st and 99th percentile):
# the usual linear-interpolation quantile of these eleven values is the
# distribution's own median and p90.
POINTS = [min(0.99, max(0.01, i / 10)) for i in range(11)]
Z90 = NormalDist().inv_cdf(0.9)


def lognormal_quantile(d, q, floor=0.0):
    med, p90 = d["median"], d["p90"]
    if med <= 0:
        return max(floor, p90 * q)
    sigma = math.log(max(p90, med) / med) / Z90
    return max(floor, med * math.exp(sigma * NormalDist().inv_cdf(q)))


def seq_bytes(n):
    """Bytes `seq 1 n` prints (digits plus a newline per number)."""
    total, digits, lo = 0, 1, 1
    while lo <= n:
        hi = min(n, 10 ** digits - 1)
        total += (hi - lo + 1) * (digits + 1)
        lo, digits = hi + 1, digits + 1
    return total


def seq_for_kb(kb):
    target = kb * 1024
    lo, hi = 1, 10_000_000
    while lo < hi:
        mid = (lo + hi) // 2
        if seq_bytes(mid) < target:
            lo = mid + 1
        else:
            hi = mid
    return lo


def scenarios(profile):
    sh = profile["shapes"]
    calls_d, out_d, kb_d = sh["model_calls_per_turn"], sh["output_tokens_per_turn"], sh["tool_output_kb"]
    calls = [max(2, round(lognormal_quantile(calls_d, q))) for q in POINTS]
    steps_total = sum(c - 1 for c in calls)
    # Tool output quantiles spread evenly over every tool step of the set,
    # interleaved with a stride so no scenario gets only small or large ones.
    stride = next(p for p in (7, 11, 13, 17, 19, 23) if math.gcd(p, steps_total) == 1)
    order = [(i * stride) % steps_total for i in range(steps_total)]
    kbs = [lognormal_quantile(kb_d, min(0.99, max(0.01, k / (steps_total - 1))), floor=0.05) for k in order]
    out, k = [], 0
    for q, n in zip(POINTS, calls):
        tokens = max(20, round(lognormal_quantile(out_d, q)))
        per_step = max(10, tokens // n)
        steps = []
        for i in range(n - 1):
            kb = kbs[k]
            k += 1
            steps.append({"turn": {
                "type": "mixed",
                "lorem_tokens": per_step,
                "calls": [{"name": "bash", "arguments": {
                    "commands": f"seq 1 {seq_for_kb(kb)}", "timeout_ms": 30000}}]}})
        steps.append({"turn": {"type": "assistant", "lorem_tokens": max(10, tokens - per_step * (n - 1))}})
        out.append({
            "name": f"coding-p{round(q * 100):02d}",
            "description": (f"A coding-agent turn at the {round(q * 100)}th percentile of model calls "
                            f"({n}) from the agents verifiers' workload/coding-profile.json. Generated by "
                            "workload/generate.py; do not edit. Needs the bash tool."),
            "defaults": {"timing": {"ttft_ms": [1500, 2500], "tokens_per_sec": 46}},
            "steps": steps,
        })
    return out


def shapes_of(scens):
    """The shapes the generated set produces, for the realism check (G6)."""
    calls, kbs, tokens = [], [], []
    for s in scens:
        calls.append(len(s["steps"]))
        t = 0
        for st in s["steps"]:
            turn = st["turn"]
            t += turn.get("lorem_tokens", 0)
            for c in turn.get("calls", []):
                n = int(c["arguments"]["commands"].split()[-1])
                kbs.append(seq_bytes(n) / 1024)
        tokens.append(t)
    return {"model_calls_per_turn": calls, "tool_output_kb": kbs, "output_tokens_per_turn": tokens}


def render(profile):
    return json.dumps(scenarios(profile), indent=1) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--profile", default=PROFILE)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    with open(a.profile) as f:
        text = render(json.load(f))
    if a.check:
        have = ""
        if os.path.exists(a.out):
            with open(a.out) as f:
                have = f.read()
        if have != text:
            sys.exit(f"{a.out} is stale: run verifiers/<agents verifier>/workload/generate.py")
        return
    with open(a.out, "w") as f:
        f.write(text)
    print(f"wrote {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
