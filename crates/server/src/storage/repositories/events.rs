    /// List message events for a session with filters applied.
    ///
    /// This method builds a dynamic SQL query based on the provided filters.
    /// DB-mappable filters (TimeRange, EventTypes, ToolName, Search, etc.) are
    /// pushed to the database for efficient filtering. Custom filters are applied
    /// in-memory after loading.
    ///
    /// Note: Injections are NOT applied here - they should be applied at the
    /// MessageRetriever layer after converting events to messages.
    pub async fn list_message_events_filtered(
        &self,
        query: &MessageQuery,
    ) -> Result<Vec<EventRow>> {
        let started = std::time::Instant::now();
        // Build dynamic SQL query
        let mut sql = String::from(
            "SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at FROM events WHERE session_id = $1",
        );

        // Collect bound values for later binding
        // We track types separately since sqlx needs typed bindings
        let mut time_from: Option<DateTime<Utc>> = None;
        let mut time_to: Option<DateTime<Utc>> = None;
        let mut event_types: Option<Vec<String>> = None;
        let mut tool_name: Option<String> = None;
        let mut search_query: Option<String> = None;
        let mut exclude_ids: Option<Vec<Uuid>> = None;
        let mut include_ids: Option<Vec<Uuid>> = None;

        // Check for EventTypes filter, else use defaults
        for filter in &query.filters {
            if let MessageFilter::EventTypes(types) = filter {
                event_types = Some(types.clone());
                break;
            }
        }

        // Default event types if not specified
        let types = event_types.unwrap_or_else(|| {
            vec![
                "input.message".to_string(),
                "output.message.completed".to_string(),
                "tool.completed".to_string(),
            ]
        });
        sql.push_str(" AND event_type = ANY($2)");

        // Build parameter index tracker (starting at 3 since $1=session_id, $2=event_types)
        let mut param_idx = 3;
        if query.after_sequence.is_some() {
            sql.push_str(&format!(" AND sequence > ${param_idx}"));
            param_idx += 1;
        }

        // Process filters
        for filter in &query.filters {
            match filter {
                MessageFilter::EventTypes(_) => {
                    // Already handled above
                }
                MessageFilter::TimeRange { from, to } => {
                    if let Some(f) = from {
                        sql.push_str(&format!(" AND created_at >= ${}", param_idx));
                        time_from = Some(*f);
                        param_idx += 1;
                    }
                    if let Some(t) = to {
                        sql.push_str(&format!(" AND created_at <= ${}", param_idx));
                        time_to = Some(*t);
                        param_idx += 1;
                    }
                }
                MessageFilter::ToolName(name) => {
                    sql.push_str(&format!(
                        " AND (event_type = 'tool.completed' AND data->>'tool_name' = ${})",
                        param_idx
                    ));
                    tool_name = Some(name.clone());
                    param_idx += 1;
                }
                MessageFilter::Search(q) => {
                    sql.push_str(&format!(
                        " AND search_vector @@ plainto_tsquery('english', ${})",
                        param_idx
                    ));
                    search_query = Some(q.clone());
                    param_idx += 1;
                }
                MessageFilter::ExcludeIds(ids) => {
                    sql.push_str(&format!(" AND id != ALL(${})", param_idx));
                    exclude_ids = Some(ids.iter().map(|id| id.uuid()).collect());
                    param_idx += 1;
                }
                MessageFilter::IncludeIds(ids) => {
                    sql.push_str(&format!(" AND id = ANY(${})", param_idx));
                    include_ids = Some(ids.iter().map(|id| id.uuid()).collect());
                    param_idx += 1;
                }
                MessageFilter::Custom(_) => {
                    // Custom filters are applied in-memory, not in SQL
                }
            }
        }

        let keep_head = query.keep_head.unwrap_or(0);
        // Whether the final SQL emits rows newest-first (needs reversing back to
        // chronological order after fetch).
        let mut needs_reverse = false;
        let effective_limit: i64;
        match (query.offset, query.limit) {
            (Some(offset), Some(limit)) => {
                effective_limit = limit.max(0);
                sql = format!(
                    "SELECT * FROM ({sql} ORDER BY sequence ASC OFFSET {}) offset_events ORDER BY sequence DESC LIMIT {}",
                    offset.max(0),
                    limit.max(0)
                );
                needs_reverse = true;
            }
            (Some(offset), None) => {
                effective_limit = -1;
                sql.push_str(&format!(" ORDER BY sequence ASC OFFSET {}", offset.max(0)));
            }
            (None, Some(limit)) if keep_head > 0 => {
                effective_limit = keep_head as i64 + limit.max(0);
                // Head+tail load: keep the first `keep_head` (the task anchor) plus
                // the latest `limit` tail, de-duplicated when the windows overlap.
                //
                // Select each end with an index-friendly `ORDER BY sequence … LIMIT`
                // over the (session_id, sequence) index — early-terminating after
                // keep_head / limit rows — then UNION on `id` (avoids equality on
                // jsonb columns) and fetch the full rows by primary key. This keeps
                // the common candidate load at O(keep_head + limit), not
                // O(total_history): infinity_context sets keep_head > 0 on every
                // load, so a full-history window sort here would scale with the
                // entire conversation. The base query is inlined into each end
                // (rather than a multiply-referenced CTE, which Postgres would
                // materialize and full-scan) so both ends keep the index. Bound
                // parameters are referenced by number, so repeating the SQL text
                // reuses the same bindings.
                sql = format!(
                    "SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at \
                     FROM events WHERE id IN (\
                       (SELECT id FROM ({sql}) head_q ORDER BY sequence ASC LIMIT {}) \
                       UNION \
                       (SELECT id FROM ({sql}) tail_q ORDER BY sequence DESC LIMIT {})\
                     ) ORDER BY sequence ASC",
                    keep_head as i64,
                    limit.max(0)
                );
            }
            (None, Some(limit)) => {
                effective_limit = limit.max(0);
                sql.push_str(&format!(" ORDER BY sequence DESC LIMIT {}", limit.max(0)));
                needs_reverse = true;
            }
            (None, None) => {
                effective_limit = MESSAGE_SAFETY_LIMIT as i64;
                // Safety cap on the otherwise-unbounded full-history read. This
                // branch is reached when MessageRetriever::load_filtered forces
                // limit/offset = None to fetch the full candidate set for
                // in-memory custom filtering / exact-count windowing. Without a
                // cap this deserializes every JSONB row for the whole session,
                // O(total_history) per call. The cap keeps the most recent N
                // rows (DESC + reverse) so the prompt window stays anchored to
                // recent history, mirroring the identical MESSAGE_SAFETY_LIMIT
                // already applied on the sibling list_message_events_limited
                // path (line ~508). Callers wanting a precise window pass an
                // explicit limit, which takes the bounded branches above.
                sql.push_str(&format!(
                    " ORDER BY sequence DESC LIMIT {}",
                    MESSAGE_SAFETY_LIMIT
                ));
                needs_reverse = true;
            }
        }

        // Build and execute query with dynamic bindings
        // sqlx doesn't support truly dynamic queries, so we need to use raw SQL
        // with all possible parameters, binding None for unused ones
        let mut db_query = sqlx::query_as::<_, EventRow>(sqlx::AssertSqlSafe(sql.as_str()))
            .bind(query.session_id.uuid())
            .bind(&types);

        if let Some(after_sequence) = query.after_sequence {
            db_query = db_query.bind(after_sequence);
        }

        // Bind parameters in order they were added to SQL
        if time_from.is_some() {
            db_query = db_query.bind(time_from);
        }
        if time_to.is_some() {
            db_query = db_query.bind(time_to);
        }
        if tool_name.is_some() {
            db_query = db_query.bind(tool_name);
        }
        if search_query.is_some() {
            db_query = db_query.bind(search_query);
        }
        if exclude_ids.is_some() {
            db_query = db_query.bind(exclude_ids);
        }
        if include_ids.is_some() {
            db_query = db_query.bind(include_ids);
        }
        let mut rows = db_query.fetch_all(&self.pool).await?;
        if needs_reverse {
            rows.reverse();
        }
        maybe_warn_slow_message_history(
            FILTERED_MESSAGE_HISTORY_EVENTS,
            started.elapsed(),
            rows.len() as u64,
            effective_limit,
        );

        Ok(rows)
    }

    /// Get preview text for multiple sessions
    ///
    /// Returns a map of session_id -> preview text (first 200 chars of first user message)
    /// This is an efficient batch query that gets previews for all provided session IDs.
    pub async fn get_session_previews(
        &self,
        session_ids: &[Uuid],
    ) -> Result<std::collections::HashMap<Uuid, String>> {
        if session_ids.is_empty() {
            return Ok(std::collections::HashMap::new());
        }

        // Use DISTINCT ON to get the first user message for each session
        // Extract text content from the JSON data structure
        let rows: Vec<(Uuid, String)> = sqlx::query_as(
            r#"
            WITH first_messages AS (
                SELECT DISTINCT ON (session_id)
                    session_id,
                    data
                FROM events
                WHERE session_id = ANY($1)
                  AND event_type = 'input.message'
                ORDER BY session_id, sequence ASC
            )
            SELECT
                session_id,
                LEFT(
                    COALESCE(
                        -- Extract text from content array: [{"type": "text", "text": "..."}]
                        data->'message'->'content'->0->>'text',
                        -- Fallback: try direct text field
                        data->'message'->>'text',
                        ''
                    ),
                    200
                ) as preview
            FROM first_messages
            WHERE data->'message'->'content'->0->>'text' IS NOT NULL
               OR data->'message'->>'text' IS NOT NULL
            "#,
        )
        .bind(session_ids)
        .fetch_all(&self.pool)
        .await?;

        Ok(rows.into_iter().collect())
    }

    /// Get output preview text for multiple sessions
    ///
    /// Returns a map of session_id -> preview text (first 200 chars of last agent message)
    /// This is an efficient batch query that gets output previews for all provided session IDs.
    pub async fn get_session_output_previews(
        &self,
        session_ids: &[Uuid],
    ) -> Result<std::collections::HashMap<Uuid, String>> {
        if session_ids.is_empty() {
            return Ok(std::collections::HashMap::new());
        }

        // Use DISTINCT ON with DESC order to get the last agent message for each session
        // Extract text content from the JSON data structure
        let rows: Vec<(Uuid, String)> = sqlx::query_as(
            r#"
            WITH last_messages AS (
                SELECT DISTINCT ON (session_id)
                    session_id,
                    data
                FROM events
                WHERE session_id = ANY($1)
                  AND event_type = 'output.message.completed'
                ORDER BY session_id, sequence DESC
            )
            SELECT
                session_id,
                LEFT(
                    COALESCE(
                        -- Extract text from content array: [{"type": "text", "text": "..."}]
                        data->'message'->'content'->0->>'text',
                        -- Fallback: try direct text field
                        data->'message'->>'text',
                        ''
                    ),
                    200
                ) as preview
            FROM last_messages
            WHERE data->'message'->'content'->0->>'text' IS NOT NULL
               OR data->'message'->>'text' IS NOT NULL
            "#,
        )
        .bind(session_ids)
        .fetch_all(&self.pool)
        .await?;

        Ok(rows.into_iter().collect())
    }
