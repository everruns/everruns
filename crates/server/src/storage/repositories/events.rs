    pub async fn create_event(&self, input: CreateEventRow) -> Result<EventRow> {
        // Atomically allocate next sequence number for this session
        // ID is generated by database using uuidv7() for monotonically increasing UUIDs
        let row = sqlx::query_as::<_, EventRow>(
            r#"
            INSERT INTO events (session_id, sequence, event_type, ts, context, data, metadata, tags)
            VALUES ($1, allocate_event_sequence($1), $2, $3, $4, $5, $6, $7)
            RETURNING id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at
            "#,
        )
        .bind(input.session_id)
        .bind(&input.event_type)
        .bind(input.ts)
        .bind(&input.context)
        .bind(&input.data)
        .bind(&input.metadata)
        .bind(&input.tags)
        .fetch_one(&self.pool)
        .await?;

        // Reporting outbox enqueue is best-effort per knowledge/evaluation/reporting.md:
        // "If an outbox write fails after canonical state commits, a periodic
        // reconciler must be able to discover and enqueue missing projection
        // work from canonical tables." Never fail the canonical event write
        // because the reporting projector queue is unavailable. No reconciler
        // job exists yet (tracked separately); until it lands, a failed
        // enqueue means the corresponding fact will remain stale until the
        // canonical row is touched again and the next enqueue succeeds.
        if let Err(e) = sqlx::query(
            r#"
            INSERT INTO reporting_outbox (
                org_id, source_type, source_id, source_version, reason, status, next_attempt_at
            )
            SELECT s.org_id, 'event', $1, $1, 'event_projection', 'pending', NOW()
            FROM sessions s
            WHERE s.id = $2
            ON CONFLICT (org_id, source_type, source_id, source_version, reason)
            DO NOTHING
            "#,
        )
        .bind(row.id.uuid().to_string())
        .bind(row.session_id.uuid())
        .execute(&self.pool)
        .await
        {
            // Look up org_id for log correlation. Failure to resolve is
            // expected when sessions row is gone or pool is unhealthy; we
            // still log the underlying error and don't propagate.
            let org_id: Option<i64> =
                sqlx::query_scalar::<_, i64>("SELECT org_id FROM sessions WHERE id = $1")
                    .bind(row.session_id.uuid())
                    .fetch_optional(&self.pool)
                    .await
                    .ok()
                    .flatten();
            warn!(
                event_id = %row.id.uuid(),
                session_id = %row.session_id.uuid(),
                org_id = ?org_id,
                event_type = %row.event_type,
                error = %e,
                "reporting outbox enqueue failed; event persisted, projection may remain stale until reconciliation lands or the source row is updated again"
            );
        }

        Ok(row)
    }

    /// Check if an input.message event with a given slack_ts already exists in a session.
    /// Used for dedup when Slack sends duplicate events (app_mention + message).
    pub async fn has_event_with_slack_ts(
        &self,
        session_id: SessionId,
        slack_ts: &str,
    ) -> Result<bool> {
        let pattern = serde_json::json!({
            "message": { "metadata": { "slack_ts": slack_ts } }
        });
        let row: (bool,) = sqlx::query_as(
            r#"
            SELECT EXISTS(
                SELECT 1 FROM events
                WHERE session_id = $1
                  AND event_type = 'input.message'
                  AND data @> $2
            )
            "#,
        )
        .bind(session_id)
        .bind(&pattern)
        .fetch_one(&self.pool)
        .await?;
        Ok(row.0)
    }

    #[allow(clippy::too_many_arguments)]
    pub async fn list_events(
        &self,
        session_id: SessionId,
        since_sequence: Option<i32>,
        since_id: Option<EventId>,
        filter_types: &[String],
        exclude_types: &[String],
        before_sequence: Option<i32>,
        limit: Option<i32>,
    ) -> Result<Vec<EventRow>> {
        // UUID v7 is NOT guaranteed monotonically increasing across concurrent inserts,
        // so we always filter and order by the dedicated sequence column.
        // When since_id is provided, resolve it to sequence via an inline subquery (PK lookup).
        // filter_types: positive filter — when non-empty, only return matching event types.
        // exclude_types: negative filter — remove matching event types from results.
        // When both are provided, filter_types narrows first, then exclude_types removes.
        //
        // Backward pagination: when `limit` is provided (with optional `before_sequence`),
        // fetch the last N events by using ORDER BY sequence DESC LIMIT N, then reverse
        // so results are returned oldest→newest.
        if let Some(limit) = limit {
            // Backward pagination: fetch last N events before a cursor
            let rows = if let Some(before_seq) = before_sequence {
                sqlx::query_as::<_, EventRow>(
                    r#"
                    SELECT * FROM (
                        SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at
                        FROM events
                        WHERE session_id = $1
                          AND sequence < $2
                          AND (cardinality($3::text[]) = 0 OR event_type = ANY($3))
                          AND (cardinality($4::text[]) = 0 OR event_type <> ALL($4))
                        ORDER BY sequence DESC
                        LIMIT $5
                    ) batch
                    ORDER BY sequence ASC
                    "#,
                )
                .bind(session_id.uuid())
                .bind(before_seq)
                .bind(filter_types)
                .bind(exclude_types)
                .bind(limit as i64)
                .fetch_all(&self.pool)
                .await?
            } else {
                // No cursor: fetch the last N events
                sqlx::query_as::<_, EventRow>(
                    r#"
                    SELECT * FROM (
                        SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at
                        FROM events
                        WHERE session_id = $1
                          AND (cardinality($2::text[]) = 0 OR event_type = ANY($2))
                          AND (cardinality($3::text[]) = 0 OR event_type <> ALL($3))
                        ORDER BY sequence DESC
                        LIMIT $4
                    ) batch
                    ORDER BY sequence ASC
                    "#,
                )
                .bind(session_id.uuid())
                .bind(filter_types)
                .bind(exclude_types)
                .bind(limit as i64)
                .fetch_all(&self.pool)
                .await?
            };
            return Ok(rows);
        }

        // Safety-limited forward query (backward compat when no limit param).
        // Cap at 10 000 rows to prevent unbounded result sets.
        const FORWARD_SAFETY_LIMIT: i64 = 10_000;
        let rows = match (since_id, since_sequence) {
            (Some(id), _) => {
                sqlx::query_as::<_, EventRow>(
                    r#"
                    SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at
                    FROM events
                    WHERE session_id = $1
                      AND sequence > (SELECT sequence FROM events WHERE id = $2)
                      AND (cardinality($3::text[]) = 0 OR event_type = ANY($3))
                      AND (cardinality($4::text[]) = 0 OR event_type <> ALL($4))
                    ORDER BY sequence ASC
                    LIMIT $5
                    "#,
                )
                .bind(session_id.uuid())
                .bind(id.uuid())
                .bind(filter_types)
                .bind(exclude_types)
                .bind(FORWARD_SAFETY_LIMIT)
                .fetch_all(&self.pool)
                .await?
            }
            (None, Some(seq)) => {
                sqlx::query_as::<_, EventRow>(
                    r#"
                    SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at
                    FROM events
                    WHERE session_id = $1 AND sequence > $2
                      AND (cardinality($3::text[]) = 0 OR event_type = ANY($3))
                      AND (cardinality($4::text[]) = 0 OR event_type <> ALL($4))
                    ORDER BY sequence ASC
                    LIMIT $5
                    "#,
                )
                .bind(session_id.uuid())
                .bind(seq)
                .bind(filter_types)
                .bind(exclude_types)
                .bind(FORWARD_SAFETY_LIMIT)
                .fetch_all(&self.pool)
                .await?
            }
            (None, None) => {
                sqlx::query_as::<_, EventRow>(
                    r#"
                    SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at
                    FROM events
                    WHERE session_id = $1
                      AND (cardinality($2::text[]) = 0 OR event_type = ANY($2))
                      AND (cardinality($3::text[]) = 0 OR event_type <> ALL($3))
                    ORDER BY sequence ASC
                    LIMIT $4
                    "#,
                )
                .bind(session_id.uuid())
                .bind(filter_types)
                .bind(exclude_types)
                .bind(FORWARD_SAFETY_LIMIT)
                .fetch_all(&self.pool)
                .await?
            }
        };

        Ok(rows)
    }

    /// Advanced event listing for debugging.
    ///
    /// Supports time range, context-id filters (turn/exec/trace), tags, tool name,
    /// full-text search, around-id windowing, and direction. Builds dynamic SQL
    /// via `QueryBuilder` so filters are pushed to the database.
    ///
    /// `since_id` and `around_id` lookups are scoped to `params.session_id` so a
    /// foreign event id silently produces an empty result rather than anchoring
    /// in another session.
    ///
    /// When `order_desc` is true, rows are returned newest-first.
    pub async fn list_events_advanced(&self, params: &ListEventsParams) -> Result<Vec<EventRow>> {
        // around_id: resolve to its sequence (within this session) and return
        // [seq-window, seq+window]. Other cursors are rejected at the command
        // layer when around_id is set.
        if let Some(anchor) = params.around_id {
            const DEFAULT_WINDOW: i32 = 50;
            const MAX_WINDOW: i32 = 500;
            let window = params.window.unwrap_or(DEFAULT_WINDOW).clamp(1, MAX_WINDOW);
            let mut qb = sqlx::QueryBuilder::<sqlx::Postgres>::new(
                "WITH anchor AS (SELECT sequence FROM events WHERE id = ",
            );
            qb.push_bind(anchor.uuid());
            qb.push(" AND session_id = ");
            qb.push_bind(params.session_id.uuid());
            qb.push(") SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at FROM events WHERE session_id = ");
            qb.push_bind(params.session_id.uuid());
            qb.push(" AND sequence BETWEEN (SELECT sequence FROM anchor) - ");
            qb.push_bind(window);
            qb.push(" AND (SELECT sequence FROM anchor) + ");
            qb.push_bind(window);
            push_common_filters(&mut qb, params);
            qb.push(" ORDER BY sequence ASC LIMIT ");
            qb.push_bind((window as i64) * 2 + 1);
            return Ok(qb
                .build_query_as::<EventRow>()
                .fetch_all(&self.pool)
                .await?);
        }

        let mut qb = sqlx::QueryBuilder::<sqlx::Postgres>::new(
            "SELECT id, session_id, sequence, event_type, ts, context, data, metadata, tags, created_at FROM events WHERE session_id = ",
        );
        qb.push_bind(params.session_id.uuid());

        // since_id resolves to a sequence subquery, scoped to this session.
        // A foreign id matches no row → `sequence > NULL` is false → empty result.
        if let Some(id) = params.since_id {
            qb.push(" AND sequence > (SELECT sequence FROM events WHERE id = ");
            qb.push_bind(id.uuid());
            qb.push(" AND session_id = ");
            qb.push_bind(params.session_id.uuid());
            qb.push(")");
        }
        if let Some(seq) = params.after_sequence {
            qb.push(" AND sequence > ");
            qb.push_bind(seq);
        }
        if let Some(seq) = params.before_sequence {
            qb.push(" AND sequence < ");
            qb.push_bind(seq);
        }

        push_common_filters(&mut qb, params);

        if params.order_desc {
            qb.push(" ORDER BY sequence DESC LIMIT ");
        } else {
            qb.push(" ORDER BY sequence ASC LIMIT ");
        }
        let limit = params.limit.unwrap_or(1_000).clamp(1, 10_000);
        qb.push_bind(limit as i64);

        Ok(qb
            .build_query_as::<EventRow>()
            .fetch_all(&self.pool)
            .await?)
    }

    /// One-shot debug summary: per-type counts + first/last timestamps.
    pub async fn events_summary(&self, session_id: SessionId) -> Result<EventsSummary> {
        type SummaryRow = (String, i64, Option<DateTime<Utc>>, Option<DateTime<Utc>>);
        let rows: Vec<SummaryRow> = sqlx::query_as(
            r#"
                SELECT event_type, COUNT(*)::bigint, MIN(ts), MAX(ts)
                FROM events
                WHERE session_id = $1
                GROUP BY event_type
                ORDER BY event_type ASC
                "#,
        )
        .bind(session_id.uuid())
        .fetch_all(&self.pool)
        .await?;

        let mut summary = EventsSummary::default();
        for (event_type, count, min_ts, max_ts) in rows {
            summary.total += count;
            if let Some(t) = min_ts {
                summary.first_ts = Some(match summary.first_ts {
                    Some(prev) if prev < t => prev,
                    _ => t,
                });
            }
            if let Some(t) = max_ts {
                summary.last_ts = Some(match summary.last_ts {
                    Some(prev) if prev > t => prev,
                    _ => t,
                });
            }
            summary.by_type.push(EventTypeCount { event_type, count });
        }
        Ok(summary)
    }

    /// Count events for a session using SELECT COUNT(*) — no row materialization.
