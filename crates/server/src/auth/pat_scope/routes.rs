// Declared access class of every hand-written `/v1` route
// (knowledge/security/pat-scopes.md, Decision 2).
//
// Decision: there is no default from the HTTP method. Every hand-written
//   route the OpenAPI document lists has exactly one row in `ROUTES`;
//   `pat_scope_coverage_test.rs` fails on a missing or a stale row. Routes the
//   document omits are classified in `UNDOCUMENTED_ROUTES` when they are
//   meant to be readable or must be explicitly `Never`; any other one stays
//   unclassified, which a narrow token will be denied.
// Decision: a non-GET row marked `Read` must also be listed in
//   `REVIEWED_NON_GET_READ`, so making a POST readable takes a second,
//   deliberate edit a reviewer sees.
// Decision: command-backed routes (`#[command(http = ..)]`) are not listed:
//   they take their class from the command. Only a `Never` row may name one,
//   to override a read-only command (Decision 4).
// Decision: `Never` (Decision 4) covers token management and the auth surface
//   (`NEVER_PREFIXES`), membership and org lifecycle, credential minting or
//   binding, and the full personal data export. A GET can be `Never`: OAuth
//   authorize and install starts bind a credential to the caller.
//
// Paths use the OpenAPI spelling in `ROUTES` and the router spelling in
// `UNDOCUMENTED_ROUTES`; parameter names are ignored when matching.

