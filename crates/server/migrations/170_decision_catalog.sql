    org_id BIGINT PRIMARY KEY REFERENCES organizations(org_id) ON DELETE CASCADE,
    model_id UUID NOT NULL,
    FOREIGN KEY (org_id, model_id) REFERENCES models(org_id, id) ON DELETE CASCADE
);

